#!/usr/bin/env python3
"""Writes the three small oracle cases under cases/ (text dictionaries only; the mesh is made by
blockMesh/topoSet/setFields in run_oracle.sh).  cases/ is committed, so this only needs re-running
after an edit here.

  tank        sealed box, 48x24x48 = 55k cells, uniform hex, constantAlphaContactAngle theta0 0 on every wall,
              pool + water column (setFields), pRefPoint, p_rgh GAMG/DIC (G4's solver set)
  tankGraded  the same sealed box sheared in x and graded in all three directions (non-orthogonal, anisotropic),
              theta0 60 on the walls / 90 on the lid, p_rgh PCG/DIC, nNonOrthogonalCorrectors 1
  open        open-top box (atmosphere patch, totalPressure p_rgh, pressureInletOutletVelocity, inletOutlet alpha),
              64x16x40 = 41k cells, theta0 30 on the walls, no pRefPoint
"""
import os

HEAD = """/*--------------------------------*- C++ -*----------------------------------*\\
| OpenFOAM v2606 | tools/mgpu_oracle: generated by gen_cases.py                           |
\\*---------------------------------------------------------------------------*/
FoamFile
{{
    version     2.0;
    format      ascii;
    class       {cls};
    {loc}object      {obj};
}}
// * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * //
"""
TAIL = "\n// ************************************************************************* //\n"


def w(case, path, obj, body, cls="dictionary", loc=""):
    p = os.path.join(HERE, "cases", case, path)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w") as f:
        f.write(HEAD.format(cls=cls, obj=obj, loc=loc) + body + TAIL)


HERE = os.path.dirname(os.path.abspath(__file__))

CASES = {
    "tank": dict(
        L=(0.2, 0.1, 0.2), N=(48, 24, 48), shear=0.0, grading="1 1 1",
        thetaWall=0, thetaLid=0, open=False, pSolver="GAMG", nNonOrth=0,
        pRef="(0.1 0.05 0.19)", column=(0.07, 0.1, 0.12), pool=0.03,
    ),
    "tankGraded": dict(
        L=(0.2, 0.1, 0.2), N=(48, 24, 48), shear=0.05, grading="4 0.4 3",
        thetaWall=60, thetaLid=90, open=False, pSolver="PCG", nNonOrth=1,
        pRef="(0.1 0.05 0.19)", column=(0.07, 0.1, 0.12), pool=0.03,
    ),
    "open": dict(
        L=(0.4, 0.1, 0.2), N=(64, 16, 40), shear=0.0, grading="1 1 1",
        thetaWall=30, thetaLid=None, open=True, pSolver="GAMG", nNonOrth=0,
        pRef=None, column=(0.12, 0.1, 0.1), pool=0.02,
    ),
}


def block_mesh(c):
    lx, ly, lz = c["L"]
    s = c["shear"]
    v = [(0, 0, 0), (lx, 0, 0), (lx, ly, 0), (0, ly, 0),
         (s, 0, lz), (lx + s, 0, lz), (lx + s, ly, lz), (s, ly, lz)]
    verts = "\n".join("    (%g %g %g)" % p for p in v)
    nx, ny, nz = c["N"]
    walls = "(0 4 7 3) (1 2 6 5) (0 1 5 4) (3 7 6 2) (0 3 2 1)"
    top = "(4 5 6 7)"
    if c["open"]:
        patches = ("    tankWall { type wall; faces (%s); }\n"
                   "    atmosphere { type patch; faces (%s); }" % (walls, top))
    else:
        patches = ("    tankWall { type wall; faces (%s); }\n"
                   "    lid { type wall; faces (%s); }" % (walls, top))
    return """scale 1;
vertices
(
%s
);
blocks ( hex (0 1 2 3 4 5 6 7) (%d %d %d) simpleGrading (%s) );
edges ();
boundary
(
%s
);
mergePatchPairs ();
""" % (verts, nx, ny, nz, c["grading"], patches)


def topo_set(c):
    lx, ly, lz = c["L"]
    big = 1.0
    z1, z2 = 0.3 * lz, 0.6 * lz
    acts = ""
    for name, lo, hi in (("zoneLow", -big, z1), ("zoneMid", z1, z2), ("zoneTop", z2, big)):
        acts += """    {
        name %s; type cellSet; action new; source boxToCell;
        box (-1 -1 %g) (2 2 %g);
    }
    { name %s; type cellZoneSet; action new; source setToCellZone; set %s; }
""" % (name, lo, hi, name, name)
    return "actions\n(\n%s);\n" % acts


def set_fields(c):
    lx, ly, lz = c["L"]
    cx, cy, cz = c["column"]
    return """defaultFieldValues ( volScalarFieldValue alpha.water 0 );
regions
(
    boxToCell { box (-1 -1 -1) (%g %g %g); fieldValues ( volScalarFieldValue alpha.water 1 ); }
    boxToCell { box (-1 -1 -1) (%g %g %g); fieldValues ( volScalarFieldValue alpha.water 1 ); }
);
""" % (lx + 1, ly + 1, c["pool"], cx, cy + 1, cz)


def fields(case, c):
    walls = "tankWall"
    cang = lambda th: ("{ type constantAlphaContactAngle; theta0 %g; limit gradient; "
                       "gradient uniform 0; value uniform 0; }" % th)
    if c["open"]:
        a_bf = "    tankWall %s\n    atmosphere { type inletOutlet; inletValue uniform 0; value uniform 0; }" % cang(c["thetaWall"])
        u_bf = ("    tankWall { type noSlip; }\n"
                "    atmosphere { type pressureInletOutletVelocity; value uniform (0 0 0); }")
        pr_bf = ("    tankWall { type fixedFluxPressure; value uniform 0; }\n"
                 "    atmosphere { type totalPressure; p0 uniform 0; value uniform 0; }")
    else:
        a_bf = "    tankWall %s\n    lid %s" % (cang(c["thetaWall"]), cang(c["thetaLid"]))
        u_bf = "    tankWall { type noSlip; }\n    lid { type noSlip; }"
        pr_bf = ("    tankWall { type fixedFluxPressure; value uniform 0; }\n"
                 "    lid { type fixedFluxPressure; value uniform 0; }")
    p_bf = "\n".join("    %s { type calculated; value uniform 0; }" % p
                     for p in (["tankWall", "atmosphere"] if c["open"] else ["tankWall", "lid"]))
    w(case, "0.orig/alpha.water.orig", "alpha.water",
      "dimensions [0 0 0 0 0 0 0];\ninternalField uniform 0;\nboundaryField\n{\n%s\n}" % a_bf,
      "volScalarField", 'location    "0";\n    ')
    w(case, "0.orig/U", "U", "dimensions [0 1 -1 0 0 0 0];\ninternalField uniform (0 0 0);\nboundaryField\n{\n%s\n}" % u_bf,
      "volVectorField", 'location    "0";\n    ')
    w(case, "0.orig/p_rgh", "p_rgh", "dimensions [1 -1 -2 0 0 0 0];\ninternalField uniform 0;\nboundaryField\n{\n%s\n}" % pr_bf,
      "volScalarField", 'location    "0";\n    ')
    w(case, "0.orig/p", "p", "dimensions [1 -1 -2 0 0 0 0];\ninternalField uniform 0;\nboundaryField\n{\n%s\n}" % p_bf,
      "volScalarField", 'location    "0";\n    ')


def constant(case, c):
    w(case, "constant/transportProperties", "transportProperties", """phases (water air);
water { transportModel Newtonian; nu 1e-06; rho 1000; }
air   { transportModel Newtonian; nu 1.48e-05; rho 1; }
sigma 0.07;
""")
    w(case, "constant/g", "g", "dimensions [0 1 -2 0 0 0 0];\nvalue (0 0 -9.81);\n",
      "uniformDimensionedVectorField", 'location    "constant";\n    ')
    w(case, "constant/turbulenceProperties", "turbulenceProperties", "simulationType laminar;\n")


def system(case, c):
    w(case, "system/blockMeshDict", "blockMeshDict", block_mesh(c))
    w(case, "system/topoSetDict", "topoSetDict", topo_set(c))
    w(case, "system/setFieldsDict", "setFieldsDict", set_fields(c))
    nn = c["nNonOrth"]
    lap = "Gauss linear limited corrected 0.5" if nn else "Gauss linear corrected"
    w(case, "system/fvSchemes", "fvSchemes", """ddtSchemes      { default Euler; }
gradSchemes     { default Gauss linear; }
divSchemes
{
    div(rhoPhi,U)    Gauss linearUpwind grad(U);
    div(phi,alpha)   Gauss vanLeer;
    div(phirb,alpha) Gauss linear;
    div(((rho*nuEff)*dev2(T(grad(U))))) Gauss linear;
}
laplacianSchemes     { default %s; }
interpolationSchemes { default linear; }
snGradSchemes        { default %s; }
""" % (lap, "limited corrected 0.5" if nn else "corrected"))
    if c["pSolver"] == "GAMG":
        ps = "solver GAMG; smoother DIC; tolerance 1e-7; relTol 0.05;"
    else:
        ps = "solver PCG; preconditioner DIC; tolerance 1e-7; relTol 0.05;"
    ref = ("    pRefPoint %s;\n    pRefValue 0;\n" % c["pRef"]) if c["pRef"] else ""
    w(case, "system/fvSolution", "fvSolution", """solvers
{
    "alpha.water.*"
    {
        nAlphaCorr      2;
        nAlphaSubCycles 1;
        cAlpha          1;
        MULESCorr       yes;
        nLimiterIter    5;
        solver          smoothSolver;
        smoother        symGaussSeidel;
        tolerance       1e-8;
        relTol          0;
    }
    "pcorr.*" { solver PCG; preconditioner DIC; tolerance 1e-8; relTol 0; }
    p_rgh { %s }
    p_rghFinal { $p_rgh; relTol 0; }
    "U.*" { solver smoothSolver; smoother symGaussSeidel; tolerance 1e-8; relTol 0; }
}
PIMPLE
{
    momentumPredictor           no;
    nOuterCorrectors            1;
    nCorrectors                 3;
    nNonOrthogonalCorrectors    %d;
%s}
""" % (ps, nn, ref))
    lx, ly, lz = c["L"]
    probes = "\n".join("            (%g %g %g)" % (lx * a, ly * b, lz * d) for a, b, d in
                       ((0.1, 0.5, 0.05), (0.3, 0.5, 0.1), (0.5, 0.5, 0.3), (0.5, 0.5, 0.6),
                        (0.9, 0.5, 0.2), (0.8, 0.2, 0.7), (0.05, 0.05, 0.05), (0.95, 0.95, 0.95)))
    fo = ""
    for z in ("zoneLow", "zoneMid", "zoneTop"):
        fo += """    liquid_%s
    {
        type volFieldValue; libs (fieldFunctionObjects);
        regionType cellZone; name %s;
        operation volIntegrate; fields (alpha.water);
        writeFields false; log false;
        writeControl timeStep; writeInterval 1;
    }
""" % (z, z)
    w(case, "system/controlDict", "controlDict", """application     interFoam;
startFrom       startTime;
startTime       0;
stopAt          endTime;
endTime         1;             // the runs are stopped by BRAE_STOP_ITER (dumpInterFoam), not by time
deltaT          1e-4;
writeControl    timeStep;
writeInterval   100000;        // writes come from BRAE_WRITE_ITERS only
purgeWrite      0;
writeFormat     binary;
writePrecision  12;
writeCompression off;
timeFormat      general;
timePrecision   10;
runTimeModifiable no;
adjustTimeStep  yes;
maxCo           0.3;
maxAlphaCo      0.3;
maxDeltaT       1e-3;

functions
{
%s    liquid_total
    {
        type volFieldValue; libs (fieldFunctionObjects);
        regionType all; operation volIntegrate; fields (alpha.water);
        writeFields false; log false;
        writeControl timeStep; writeInterval 1;
    }
    probes
    {
        type probes; libs (sampling);
        fields (alpha.water U p_rgh);
        fixedLocations true;
        writeControl timeStep; writeInterval 1;
        probeLocations
        (
%s
        );
    }
    minMaxU
    {
        type fieldMinMax; libs (fieldFunctionObjects);
        fields (U); mode magnitude;
        writeControl timeStep; writeInterval 1;
        log false;
    }
    never
    {
        type runTimeControl; libs (utilityFunctionObjects);
        conditions
        {
            speedReached
            {
                type minMax; functionObject liquid_total;
                fields (volIntegrate(alpha.water));
                mode maximum; value 1e9;
            }
        }
        satisfiedAction end;
    }
}
""" % (fo, probes))
    for n in (2, 4, 8):
        w(case, "system/decomposeParDict.scotch%d" % n, "decomposeParDict",
          "numberOfSubdomains %d;\nmethod scotch;\n" % n)
    w(case, "system/decomposeParDict.simple2", "decomposeParDict",
      "numberOfSubdomains 2;\nmethod simple;\nsimpleCoeffs { n (1 1 2); }\n")
    w(case, "system/decomposeParDict.simple4", "decomposeParDict",
      "numberOfSubdomains 4;\nmethod simple;\nsimpleCoeffs { n (1 2 2); }\n")
    w(case, "system/decomposeParDict.simple8", "decomposeParDict",
      "numberOfSubdomains 8;\nmethod simple;\nsimpleCoeffs { n (2 2 2); }\n")
    w(case, "system/decomposeParDict.hier8", "decomposeParDict",
      "numberOfSubdomains 8;\nmethod hierarchical;\nhierarchicalCoeffs { n (2 2 2); order zyx; }\n")
    w(case, "system/decomposeParDict.hier4", "decomposeParDict",
      "numberOfSubdomains 4;\nmethod hierarchical;\nhierarchicalCoeffs { n (2 1 2); order zyx; }\n")


for name, c in CASES.items():
    constant(name, c)
    fields(name, c)
    system(name, c)
    print("wrote cases/" + name)
