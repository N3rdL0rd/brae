namespace crdd {
struct dd { double h, l; };
__device__ __forceinline__ dd two_sum(double a, double b) { double s = __dadd_rn(a, b); double bb = __dsub_rn(s, a); double e = __dadd_rn(__dsub_rn(a, __dsub_rn(s, bb)), __dsub_rn(b, bb)); return {s, e}; }
__device__ __forceinline__ dd fast_two_sum(double a, double b) { double s = __dadd_rn(a, b); double e = __dsub_rn(b, __dsub_rn(s, a)); return {s, e}; }
__device__ __forceinline__ dd two_prod(double a, double b) { double p = __dmul_rn(a, b); return {p, __fma_rn(a, b, -p)}; }
__device__ __forceinline__ dd add(dd a, dd b) {
  dd s = two_sum(a.h, b.h), t = two_sum(a.l, b.l);
  double c = __dadd_rn(s.l, t.h);
  dd v = fast_two_sum(s.h, c);
  double w = __dadd_rn(t.l, v.l);
  return fast_two_sum(v.h, w);
}
__device__ __forceinline__ dd neg(dd a) { return {-a.h, -a.l}; }
__device__ __forceinline__ dd sub(dd a, dd b) { return add(a, neg(b)); }
__device__ __forceinline__ dd mul(dd a, dd b) {
  dd c = two_prod(a.h, b.h);
  double tl0 = __dmul_rn(a.l, b.l);
  double tl1 = __fma_rn(a.h, b.l, tl0);
  double cl2 = __fma_rn(a.l, b.h, tl1);
  double cl3 = __dadd_rn(c.l, cl2);
  return fast_two_sum(c.h, cl3);
}
__device__ __forceinline__ dd mul_d(dd a, double b) {
  dd c = two_prod(a.h, b);
  double cl3 = __fma_rn(a.l, b, c.l);
  return fast_two_sum(c.h, cl3);
}
__device__ __forceinline__ dd sqrt_dd(dd a) {
  double y = sqrt(a.h);
  dd p = two_prod(y, y);
  double rem = __dadd_rn(__dsub_rn(__dsub_rn(a.h, p.h), p.l), a.l);
  return fast_two_sum(y, __dmul_rn(rem, __dmul_rn(0.5, 1.0 / y)));
}

// sin(r) / cos(r) for |r| <= ~0.8 (dd)
__device__ __forceinline__ dd cos_kernel(dd r) {
  dd r2 = mul(r, r);
  // tail j>=9 in double: sum_{j>=9} (-1)^j r2^j/(2j)!  (as polynomial in r2: Horner)
  double x2 = r2.h;
  double tail = 0.0;
  for (int j = 16; j >= 9; --j) tail = __fma_rn(tail, x2, (j & 1) ? -INVF_H[2 * j] : INVF_H[2 * j]);
  // value of sum_{j>=9}: tail already Horner-evaluated as c9 + x2*(c10 + ...)? we iterate descending so tail = c16 ... c9 ; need reverse
  dd acc = {tail, 0.0};
  for (int j = 8; j >= 0; --j) {
    acc = mul(acc, r2);
    double ch = (j & 1) ? -INVF_H[2 * j] : INVF_H[2 * j], cl = (j & 1) ? -INVF_L[2 * j] : INVF_L[2 * j];
    acc = add(acc, dd{ch, cl});
  }
  return acc;
}
__device__ __forceinline__ dd sin_kernel(dd r) {
  dd r2 = mul(r, r);
  double x2 = r2.h;
  double tail = 0.0;
  for (int j = 16; j >= 9; --j) tail = __fma_rn(tail, x2, (j & 1) ? -INVF_H[2 * j + 1] : INVF_H[2 * j + 1]);
  dd acc = {tail, 0.0};
  for (int j = 8; j >= 0; --j) {
    acc = mul(acc, r2);
    double ch = (j & 1) ? -INVF_H[2 * j + 1] : INVF_H[2 * j + 1], cl = (j & 1) ? -INVF_L[2 * j + 1] : INVF_L[2 * j + 1];
    acc = add(acc, dd{ch, cl});
  }
  return mul(acc, r);
}
// reduce double y (|y| < ~100) -> r = y - k*pi/2, |r|<=pi/4+; returns k
__device__ __forceinline__ dd reduce(double y, int &k) {
  double kd = rint(__dmul_rn(y, 0x1.45F306DC9C883p-1));
  k = (int)kd;
  dd r = {y, 0.0};
  for (int i = 0; i < 4; ++i) r = add(r, neg(two_prod(kd, PIO2[i])));
  return r;
}
// cos of double y as dd
__device__ __forceinline__ dd cos_dd_of(double y) {
  int k; dd r = reduce(y, k);
  dd res;
  switch (k & 3) {
    case 0: res = cos_kernel(r); break;
    case 1: res = neg(sin_kernel(r)); break;
    case 2: res = neg(cos_kernel(r)); break;
    default: res = sin_kernel(r); break;
  }
  return res;
}
__device__ __forceinline__ void sincos_dd_of(double y, dd &s, dd &c) {
  int k; dd r = reduce(y, k);
  dd sr = sin_kernel(r), cr = cos_kernel(r);
  switch (k & 3) {
    case 0: s = sr; c = cr; break;
    case 1: s = cr; c = neg(sr); break;
    case 2: s = neg(sr); c = neg(cr); break;
    default: s = neg(cr); c = sr; break;
  }
}
__device__ __forceinline__ double cos_cr(double y) {
  if (y != y) return __longlong_as_double(__double_as_longlong(y) | 0x0008000000000000LL);
  if (!(fabs(y) < 1e4)) return __longlong_as_double(0xfff8000000000000LL);
  if (fabs(y) < 0x1p-30) return 1.0;
  dd r = cos_dd_of(y);
  return __dadd_rn(r.h, r.l);
}
__device__ __forceinline__ double acos_cr(double x) {
  if (x != x) return __longlong_as_double(__double_as_longlong(x) | 0x0008000000000000LL);
  double a = fabs(x);
  if (a > 1.0) return __longlong_as_double(0x7ff8000000000000LL);
  if (a == 1.0) return (x > 0) ? 0.0 : __dadd_rn(PI4L[0], 0.0);
  double y0 = glibcport::acos_glibc<true>(a);
  dd om = two_sum(1.0, -a), op = two_sum(1.0, a);
  dd s = sqrt_dd(mul(om, op));
  dd sy, cy; sincos_dd_of(y0, sy, cy);
  dd F = sub(mul_d(sy, a), mul(s, cy));
  dd Y = sub(dd{y0, 0.0}, F);
  if (x < 0) Y = sub(dd{PI4L[0], PI4L[1]}, Y);   // pi - acos(|x|)
  return __dadd_rn(Y.h, Y.l);
}
